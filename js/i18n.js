  window.NOVA_I18N = {
    translations,
    locale,
    t(path) {
      return path
        .split(".")
        .reduce((value, key) => value?.[key], translations[this.locale]);
    },
    dynamic(collection, index, field) {
      if (collection === "stats") {
        return Object.values(translations[this.locale].stats)[index];
      }
      const value = translations[this.locale]?.[collection]?.[index];
      return Array.isArray(value) ? value[field] : value;
    },
    setLocale(nextLocale) {
      if (!translations[nextLocale]) return;
      this.locale = nextLocale;
      localStorage.setItem("nova-locale", nextLocale);
      document.documentElement.lang = nextLocale;
      document.documentElement.dir = nextLocale === "ar" ? "rtl" : "ltr";
      document.title = this.t("meta.title");
      document.querySelector('meta[name="description"]').content =
        this.t("meta.description");
      document.dispatchEvent(
        new CustomEvent("nova-language-change", { detail: nextLocale }),
      );
    },
  };
